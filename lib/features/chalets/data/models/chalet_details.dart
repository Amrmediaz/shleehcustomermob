    required String name,
    required String rentFullday,
    required String rentFulldayDisCount,
    required String rentHalfday,
    required String rentHalfdayDisCount,
    required String buldingDescrption,
    required int minDays,

    required String note,
    required String state,
    required String gouvernate,
    required String lat,
    required String lng,
    required bool showComments,
    required bool isActive,
    required bool stopBook,
    required String offDayPriceFullday,
    required String offDayPriceHalfday,
    required String crreatedDate,
    required String rentweekend,
    required bool acceptDeposit,
    required bool breakfastenabled,
    required bool fulldayDiscountenabled,
    required String fulldayDiscountenabledText,
    required String insuranceamount,
    required int rateAverage,
    required List<Map<String, dynamic>> buldingImages,
    required List<Map<String, dynamic>> buldingService,
    required List<dynamic> discountfullDate,
    required List<dynamic> discountHalfDate,
    required List<Map<String, dynamic>> buldingComment,
    required int apartmentOwnerId,
    bool todayOfferEnabled = false,
    int todayOfferPercent = 0,
    int todayOfferTriggerHour = 12,
    bool todayOfferActive = false,
  }) : super(
    id: id,
    name: name,
    rentFullday: rentFullday,
    rentFulldayDisCount: rentFulldayDisCount,
    rentHalfday: rentHalfday,
    rentHalfdayDisCount: rentHalfdayDisCount,
    buldingDescrption: buldingDescrption,
    note: note,
    state: state,
    gouvernate: gouvernate,
    lat: lat,
    lng: lng,
    showComments: showComments,
    isActive: isActive,
    stopBook: stopBook,
    minDays: minDays,
    offDayPriceFullday: offDayPriceFullday,
    offDayPriceHalfday: offDayPriceHalfday,
    crreatedDate: crreatedDate,
    rentweekend: rentweekend,
    acceptDeposit: acceptDeposit,
    breakfastenabled: breakfastenabled,
    fulldayDiscountenabled: fulldayDiscountenabled,
    fulldayDiscountenabledText: fulldayDiscountenabledText,
    insuranceamount: insuranceamount,
    rateAverage: rateAverage,
    buldingImages: buldingImages,
    buldingService: buldingService,
    discountfullDate: discountfullDate,
    discountHalfDate: discountHalfDate,
    buldingComment: buldingComment,
    apartmentOwnerId: apartmentOwnerId,
    todayOfferEnabled: todayOfferEnabled,
    todayOfferPercent: todayOfferPercent,
    todayOfferTriggerHour: todayOfferTriggerHour,
    todayOfferActive: todayOfferActive,
  );

  factory ChaletDetailsModel.fromJson(Map<String, dynamic> json) {
    return ChaletDetailsModel(
      id: json['id'],
      name: json['name'],
      minDays : json['minDays'] ?? 0,
      rentFullday: json['rentFullday'],
      rentFulldayDisCount: json['rentFulldayDisCount'] ?? "",
      rentHalfday: json['rentHalfday'],
      rentHalfdayDisCount: json['rentHalfdayDisCount'] ?? "",
      buldingDescrption: json['buldingDescrption'],
      note: json['note'],
      state: json['state'],
      gouvernate: json['gouvernate'],
      lat: json['lat'],
      lng: json['lng'],
      showComments: json['showComments'],
      isActive: json['isActive'],
      stopBook: json['stopBook'],
      offDayPriceFullday: json['offDayPriceFullday'] ?? "",
      offDayPriceHalfday: json['offDayPriceHalfday'] ?? "",
      crreatedDate: json['crreatedDate'] ?? "",
      rentweekend: json['rentweekend'] ?? "",
      acceptDeposit: json['acceptDeposit'] ?? false,
      breakfastenabled: json['breakfastenabled'] ?? false,
      fulldayDiscountenabled: json['fulldayDiscountenabled'] ?? "",
      fulldayDiscountenabledText: json['fulldayDiscountenabledText'] ?? "",
      insuranceamount: json['insuranceamount'] ?? "",
      rateAverage: json['rateAverage'],
      buldingImages: List<Map<String, dynamic>>.from(json['buldingImages']),
      buldingService: List<Map<String, dynamic>>.from(json['buldingService']),
      discountfullDate: List<dynamic>.from(json['discountfullDate']),
      discountHalfDate: List<dynamic>.from(json['discountHalfDate']),
      buldingComment: List<Map<String, dynamic>>.from(json['buldingComment']),
      apartmentOwnerId: json['apartmentOwnerId'],
      todayOfferEnabled: json['todayOfferEnabled'] as bool? ?? false,
      todayOfferPercent: (json['todayOfferPercent'] as num?)?.toInt() ?? 0,
      todayOfferTriggerHour:
          (json['todayOfferTriggerHour'] as num?)?.toInt() ?? 12,
      todayOfferActive: json['todayOfferActive'] as bool? ?? false,
    );
  }

